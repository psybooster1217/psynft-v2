#!/usr/bin/env bash
# ---------------------------------------------------------------------------
# Local sandbox for testing the PsyNFT V2 admin UI end-to-end.
#
#   ./sandbox/start.sh            # fresh chain (default) — no external RPC needed
#   ./sandbox/start.sh roles      # fresh chain, owner=#0, core=#1, treasury=#2 (role separation)
#   ./sandbox/start.sh migrated   # fork mainnet + run the real 33-holder migration
#
# It spins up a local anvil chain (chainId 31337), deploys PsyNFTV2 (by default with
# owner = core = treasury = anvil account #0, so ONE account can drive every button),
# writes ui/.env.local so the UI auto-targets it, and starts the UI dev server.
# In the UI, pick "Sandbox account…" (top right): anvil signs for its dev accounts, so no
# browser wallet or private key is needed. "Act as" impersonates any address (e.g. the
# real Main Safe on a mainnet fork).
#
# Stop everything with Ctrl-C (anvil is torn down automatically).
# Run in Git Bash / WSL / macOS / Linux. Foundry + Node required.
# ---------------------------------------------------------------------------
set -euo pipefail

export PATH="$HOME/.foundry/bin:$PATH"
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

MODE="${1:-fresh}"
RPC_LOCAL="http://127.0.0.1:8545"
CHAIN_ID=31337

# anvil account #0 — the canonical dev key (public, test-only, safe to hardcode).
ACCT0_ADDR="0xf39Fd6e51aad88F6F4ce6aB8827279cffFb92266"
ACCT0_KEY="0xac0974bec39a17e36ba4a6b4d238ff944bacb478cbed5efcae784d7bf4f2ff80"
ACCT1_ADDR="0x70997970C51812dc3A010C7d01b50e0d17dc79C8"
ACCT2_ADDR="0x3C44CdDdB6a900fa2b585dd299e03d12FA4293BC"
# V1's metadata folder, gateway-independent. (V1 pointed at a dedicated Pinata host that no
# longer resolves: audit 2026-10 META-1.) Production uses the re-pinned folder in metadata/CID-v2.txt.
BASE_URI_DEFAULT="ipfs://bafybeia5k2sgu3fkeyqodrmg43b7tbhd5fsmdgf7e4b34hiwrbeaybovcy/"

for tool in anvil forge node curl; do
  command -v "$tool" >/dev/null 2>&1 || { echo "ERROR: '$tool' not found on PATH."; exit 1; }
done

# --- start anvil ---------------------------------------------------------
ANVIL_ARGS=(--chain-id "$CHAIN_ID" --silent)
if [ "$MODE" = "migrated" ]; then
  FORK="${MAINNET_RPC_URL:-https://ethereum-rpc.publicnode.com}"
  ANVIL_ARGS+=(--fork-url "$FORK")
  echo "▶ anvil: forking mainnet ($FORK) as chainId $CHAIN_ID"
elif [ "$MODE" = "fresh" ] || [ "$MODE" = "roles" ]; then
  echo "▶ anvil: fresh chain (chainId $CHAIN_ID)"
else
  echo "ERROR: unknown mode '$MODE' (use 'fresh', 'roles' or 'migrated')"; exit 1
fi

anvil "${ANVIL_ARGS[@]}" &
ANVIL_PID=$!
cleanup() { echo; echo "▶ shutting down sandbox…"; kill "$ANVIL_PID" 2>/dev/null || true; }
trap cleanup EXIT INT TERM

echo -n "▶ waiting for anvil"
for _ in $(seq 1 30); do
  if curl -s "$RPC_LOCAL" -H 'content-type: application/json' \
       --data '{"jsonrpc":"2.0","id":1,"method":"eth_blockNumber","params":[]}' 2>/dev/null | grep -q result; then
    echo " ✓"; break
  fi
  echo -n "."; sleep 1
done

# --- deploy --------------------------------------------------------------
export PRIVATE_KEY="$ACCT0_KEY"
export NEW_CORE="$ACCT0_ADDR"
export NEW_TREASURY="$ACCT0_ADDR"
if [ "$MODE" = "roles" ]; then
  export NEW_CORE="$ACCT1_ADDR"
  export NEW_TREASURY="$ACCT2_ADDR"
fi
export BASE_URI="${BASE_URI:-$BASE_URI_DEFAULT}"

echo "▶ deploying PsyNFTV2 (owner=$ACCT0_ADDR core=$NEW_CORE treasury=$NEW_TREASURY)…"
forge script script/Deploy.s.sol --rpc-url "$RPC_LOCAL" --broadcast 2>&1 | grep -E "deployed|WARNING" || true
V2="$(node -e "console.log(require('./broadcast/Deploy.s.sol/${CHAIN_ID}/run-latest.json').transactions[0].contractAddress)")"
export PSYNFT_V2="$V2"
echo "  → PsyNFTV2 @ $V2"

if [ "$MODE" = "migrated" ]; then
  echo "▶ running migration (re-mints the 33 holders from snapshot/holders.json)…"
  forge script script/Migrate.s.sol --rpc-url "$RPC_LOCAL" --broadcast 2>&1 | grep -E "migrating|preflight|finalized|tokenId" || true
fi

# --- point the UI at it --------------------------------------------------
cat > ui/.env.local <<EOF
# Auto-generated by sandbox/start.sh — safe to delete. Git-ignored.
VITE_CONTRACT_ADDRESS=$V2
VITE_RPC_URL=$RPC_LOCAL
VITE_CHAIN_ID=$CHAIN_ID
EOF
echo "▶ wrote ui/.env.local (VITE_CONTRACT_ADDRESS + local RPC)"

cat <<BANNER

──────────────────────────────────────────────────────────────────────────
  SANDBOX READY  ·  mode: $MODE
──────────────────────────────────────────────────────────────────────────
  Chain      : $RPC_LOCAL   (chainId $CHAIN_ID)
  Contract   : $V2
  UI         : http://localhost:5173   (address pre-filled)

  To WRITE: in the UI pick "Sandbox account…" (top right). No browser wallet needed.
     #0 = owner$( [ "$MODE" = "roles" ] && echo ", #1 = core, #2 = treasury" || echo " + core + treasury")
  (MetaMask also works: add RPC $RPC_LOCAL / chainId $CHAIN_ID and import the anvil
   dev key $ACCT0_KEY — TEST ONLY, never use on a real network.)

  Step-by-step tests: docs/TESTING_HANDBOOK.md
  Ctrl-C stops the chain and the UI.
──────────────────────────────────────────────────────────────────────────

BANNER

# --- start the UI (foreground; Ctrl-C tears down anvil via the trap) -----
npm --prefix ui install >/dev/null 2>&1 || true
npm --prefix ui run dev
